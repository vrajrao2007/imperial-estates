/**
 * Format price in Indian Rupee format (Crores & Lakhs).
 * Examples: ₹4.5 Cr, ₹18.25 Cr, ₹95 L
 */
export function formatPrice(price: number): string {
  if (price >= 10_000_000) {
    const cr = price / 10_000_000;
    // If integer, no decimals; else up to 2 decimals
    const formatted = cr % 1 === 0 ? cr.toFixed(0) : cr.toFixed(2).replace(/\.?0+$/, "");
    return `₹${formatted} Cr`;
  }
  if (price >= 100_000) {
    const l = price / 100_000;
    const formatted = l % 1 === 0 ? l.toFixed(0) : l.toFixed(1).replace(/\.?0+$/, "");
    return `₹${formatted} L`;
  }
  return `₹${price.toLocaleString("en-IN")}`;
}

/** Full Indian numbering format with Rupee symbol, e.g. ₹4,50,00,000 */
export function formatPriceFull(price: number): string {
  return `₹${price.toLocaleString("en-IN")}`;
}

/** Get unique cities from dataset */
export function getCities(): string[] {
  return [...new Set(properties.map((p) => p.city))].sort();
}

/** Get unique Hyderabad localities */
export function getLocalities(): string[] {
  return [...new Set(properties.map((p) => p.location))].sort();
}


/** Get unique Hyderabad areas (broader zones) with property counts */
export function getAreas(): { name: string; count: number }[] {
  const map = new Map<string, number>();
  for (const p of properties) {
    map.set(p.area, (map.get(p.area) || 0) + 1);
  }
  return [...map.entries()]
    .map(([name, count]) => ({ name, count }))
    .sort((a, b) => b.count - a.count);
}